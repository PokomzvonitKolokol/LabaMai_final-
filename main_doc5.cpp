// Данная программа проверяет является ли переданная строка корректным
// оператором сравнения :
//   "<", ">", "==", "!=", "<=", ">="
// 
// Программа использует конечный автомат
// 
// Структура программы:
// 
// 1. enum State - перечисление возможных состояний автомата:
//     START    - начальное состояние (ещё не прочитан ни один символ)
//     LT       - прочитан символ '<'; ожидается возможный '='
//     GT       - прочитан символ '>'; ожидается возможный '='
//     EQ       - прочитан символ '='; ожидается возможный второй '='
//     EXCL    - прочитан символ '!'; ожидается '='
//     EQ_EQ    - успешно распознан оператор "=="
//     EXCL_EQ - успешно распознан оператор "!="
//     LT_EQ    - успешно распознан оператор "<="
//     GT_EQ   - успешно распознан оператор ">="
//     REJECT   - недопустимая последовательность символов; ошибка
// 
// 2. bool isComparisonOperator(const std::string& s)
//    проверяет является ли строка s допустимым оператором сравнения.
//    Вход: строка s 
//    Выход: true — если s совпадает с одним из  операторов,
//           false — в противном случае (включая пустую строку или лишние символы).
//    Логика: проход по каждому символу строки с обновлением состояния автомата.
//            При переходе в состояние REJECT функция сразу возвращает false.
//            После обработки всей строки проверяется, находится ли автомат
//            в одном из допустимых финальных состояний.
// 
// 3. int main()
//    Назначение: демонстрация работы функции isComparisonOperator
//    выводит:
//        "<строка>" -> оператор
//    или
//        "<строка>" -> не оператор