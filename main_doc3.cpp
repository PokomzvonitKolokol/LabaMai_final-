// Назначение: Подсчитывает количество вхождений заданной подстроки в строку (включая перекрывающиеся вхождения).
//
// Структура программы:
//   Единственная функция: main().
//   Используются стандартные библиотеки: <iostream> и <string>.
//   Ввод строк осуществляется с помощью std::getline() — поддерживает пробелы и многословный ввод.
//
// Основные переменные:
//   std::string str
//        основная строка, в которой выполняется поиск.
//   std::string substr
//       искомая подстрока.
//   int count
//       счётчик найденных вхождений (инициализируется нулём).
//   size_t pos
//       текущая позиция поиска в строке (начинается с 0).
//
// Алгоритм работы:
//   1. Пользователь вводит основную строку (включая пробелы).
//   2. Пользователь вводит подстроку для поиска.
//   3. Если подстрока пуста — выводится сообщение и программа завершается с результатом 0.
//   4. Используется цикл while с методом std::string::find():
//        find(substr, pos) ищет подстроку, начиная с позиции pos.
//        При нахождении вхождения (pos != npos) счётчик увеличивается.
//       pos смещается на 1 (а не на substr.length()), чтобы находить **перекрывающиеся** вхождения.
//   5. После завершения поиска выводится общее количество вхождений.
//
// Особенности:
//    Поддержка перекрывающихся вхождений:
//         например, в строке "aaaa" подстрока "aa" встречается 3 раза.
//    Используется size_t для индексации — безопасно для длинных строк.
//
// Пример работы:
//   Введите строку: aaaa
//   Введите подстроку для поиска: aa
//   Количество вхождений подстроки: 3
//
//   Введите строку: abababa
//   Введите подстроку для поиска: aba
//   Количество вхождений подстроки: 3