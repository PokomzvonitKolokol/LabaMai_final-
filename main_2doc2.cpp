// Назначение: Программа считывает список целых чисел и выводит только чётные из них.
//
// Структура программы:
//    Главная функция main() — единственная функция программы.
//    Используются только стандартные средства ввода-вывода (cin, cout).
//    Массив фиксированного размера , ограничение — 100 элементов.
//
// Основные переменные:
//   const int MAX_SIZE = 100
//        максимальное допустимое количество элементов (ограничение размера массива).
//   int arr[MAX_SIZE]
//        массив для хранения введённых целых чисел.
//   int n
//        количество введённых чисел (должно быть: 1 ≤ n ≤ MAX_SIZE).
//
// Алгоритм работы:
//   1. Пользователь вводит количество чисел n.
//   2. Проверяется корректность n: должно быть > 0 и ≤ MAX_SIZE.
//      При нарушении — вывод ошибки и завершение с кодом 1.
//   3. Пользователь вводит n целых чисел, которые сохраняются в arr.
//   4. Программа проходит по массиву и для каждого элемента arr[i]:
//        - если arr[i] % 2 == 0 (остаток от деления на 2 равен нулю),
//          число считается чётным и выводится на экран.
//   5. Каждое чётное число выводится на отдельной строке.
//
// Особенности:
//    Отрицательные чётные числа (например, -4, -2) также распознаются как чётные.
//    Ноль (0) считается чётным и будет выведен.
//    Некорректный ввод (например, буквы вместо чисел) (cin).
//
// Пример :
//   Введите кол-во чисел в списке: 5
//   Введите 5 целых чисел:
//   1 2 3 4 5
//
//
//   2
//   4